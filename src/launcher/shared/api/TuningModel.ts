  leaveDwellMs: 350,
  /** ホームのアイコンをフォルダ内へ持ち込んだあと、枠の外に居続けたらフォルダを閉じるまでの時間(ms) */
  closeOutsideMs: 700,

  // ---- アニメーション ----
  /** アイコンが別の位置へ動くときのアニメーション時間(ms) */
  moveAnimationMs: 320,
